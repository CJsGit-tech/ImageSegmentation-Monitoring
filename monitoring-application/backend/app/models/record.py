from datetime import datetime

from sqlalchemy import BigInteger, Boolean, Double, ForeignKey, Index, String, UniqueConstraint, false
from sqlalchemy.dialects.mysql import DATETIME
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base
from app.models.user import User

TITLE_MAX_LENGTH = 255
CATEGORY_MAX_LENGTH = 100
# Titles search and sort loosely. Categories keep every spelling apart, because each
# distinct value is its own option in the list filter (PRD-04-R9) and its own range key.
TABLE_COLLATION = "utf8mb4_uca1400_ai_ci"
CATEGORY_COLLATION = "utf8mb4_uca1400_as_cs"


class Record(Base):
    __tablename__ = "records"
    __table_args__ = (
        Index("ix_records_category_timestamp", "category", "timestamp"),
        Index("ix_records_is_anomaly_timestamp", "is_anomaly", "timestamp"),
        # Data analysis (LB-331): statistics and trends read only this index.
        Index("ix_records_category_timestamp_value", "category", "timestamp", "value", "is_anomaly"),
        # System-record history (LB-336): creator IS NULL, time range, category, anomaly from the index.
        Index("ix_records_creator_timestamp_category", "created_by_user_id", "timestamp", "category", "is_anomaly"),
        # Several NULLs are allowed, so imported and generated records are not affected.
        UniqueConstraint("client_request_id", "created_by_user_id", name="uq_records_client_request"),
        {"mariadb_charset": "utf8mb4", "mariadb_collate": TABLE_COLLATION},
    )

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    title: Mapped[str] = mapped_column(String(TITLE_MAX_LENGTH), nullable=False, index=True)
    value: Mapped[float] = mapped_column(Double, nullable=False, index=True)
    category: Mapped[str] = mapped_column(
        String(CATEGORY_MAX_LENGTH, collation=CATEGORY_COLLATION), nullable=False, index=True
    )
    # Naive UTC with microseconds.
    timestamp: Mapped[datetime] = mapped_column(DATETIME(fsp=6), nullable=False, index=True)
    # NULL means generated by the system (PRD-07-R10). RESTRICT, because SET NULL would
    # silently turn a removed user's records into system records.
    created_by_user_id: Mapped[int | None] = mapped_column(
        BigInteger, ForeignKey("users.id", ondelete="RESTRICT"), nullable=True
    )
    # Stored with the record (PRD-09-R3). Set through app.records.anomaly.
    is_anomaly: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False, server_default=false())

    # Sent by a client that may retry, so that a retried create cannot add a second record.
    client_request_id: Mapped[str | None] = mapped_column(String(36), nullable=True)

    # Load explicitly: lazy loading cannot work on an async session.
    creator: Mapped[User | None] = relationship(lazy="raise")
